# глобальный цикл, чтобы не перезапускать программу 
while(1):

    # вывод запроса в консоль 
    # \n - отступ строки 
    print ( '\n\nВведите вашу зарплатку: ')
    # ввод строки через input, 
    # преобразование строки в число для мат. операций 

    # проверка на любые ошибки, чтобы программа не ломалась, 
    # если пользователь дурачок и ввел не число 
    try:
        money = float(input())
    except Exception as e: 
        print (f'Нужно ввести число. Ошибка: {e}')
        continue

    # проверка, что зарплата вообще есть 
    if (money <= 0):
        print ('Нищета')
        # прекращение текущего цикла 
        continue
        
    # вывод запроса в консоль 
    print ( 'Введите вашу стажик: ')
    # ввод строки через input, 
    # преобразование строки в число для лог. операций 

    # еще проверка
    try:
        years = float(input())
    except Exception as e: 
        print ('Нужно ввести число. Ошибка: {e}')
        continue

    # надбавка
    bonus = 0

    # если стаж от 2 до 5 лет, надбавка составляет 2%
    if 2 < years < 5:
        bonus = calc_bonus(money, 2)
    # если стаж от 5 до 10 лет - 5%
    elif years < 10:
        bonus = calc_bonus(money, 5)

    # вывести надбавку и сумму к выплате
    print ( 'Надбавка: ' + str(bonus) +
            '. Всего к выплате: ' + str(money + bonus) )
